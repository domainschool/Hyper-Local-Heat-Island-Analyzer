// Helper to generate 24-hour diurnal profile
function makeDiurnal(peakTract: number, peakBaseline: number, peakPark: number) {
  const hours = ['00:00', '03:00', '06:00', '09:00', '12:00', '15:00', '18:00', '21:00'];
  // Tract retains heat longer at night (high thermal mass)
  const tractOffsets = [-9, -12, -14, -4, 0, -1, -5, -7];
  const baseOffsets = [-12, -15, -17, -5, 0, -2, -8, -10];
  const parkOffsets = [-16, -19, -21, -6, 0, -3, -11, -14];

  return hours.map((hour, idx) => ({
    hour,
    tractTemp: Number((peakTract + tractOffsets[idx]).toFixed(1)),
    baselineTemp: Number((peakBaseline + baseOffsets[idx]).toFixed(1)),
    parkTemp: Number((peakPark + parkOffsets[idx]).toFixed(1)),
  }));
}

